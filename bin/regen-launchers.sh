#!/usr/bin/env bash
# foundry/bin/regen-launchers.sh
#
# Regenerate the Collie launchers.toml — the file that turns one-tap phone
# presses (and the `work-board refresh` button) into actual kanban board
# launches. Reads the project list from jott, so a new project becomes a
# button the moment `herdr server reload-config` runs.
#
# Output destinations (created if missing):
#   <herdr-collie-config>/launchers.toml              what herdr reads
#   <dotfiles>/.../herdr.collie/launchers.toml       tracked copy for re-stows
#
# Layout note: herdr.collie's plugin config dir lives outside the foundry
# repo. The dotfiles path keeps the buttons across `make linux`; if the
# dotfiles copy is missing (fresh install, no stow yet), we still write the
# canonical file so the buttons work today, and warn.
#
# Re-running this script is idempotent: the file content is fully derived
# from `jott task projects --json` plus a fixed list of always-on rows, so
# regenerating produces a byte-identical file. `diff` against the previous
# version is a useful safety net in CI.

set -euo pipefail

# Resolve canonical herdr.collie config dir.
HERDR_COLLIE_CONFIG_DEFAULT="$HOME/.config/herdr/plugins/config/herdr.collie"
if command -v herdr >/dev/null 2>&1; then
  HERDR_COLLIE_CONFIG_DEFAULT="$(herdr plugin config-dir herdr.collie 2>/dev/null || echo "$HERDR_COLLIE_CONFIG_DEFAULT")"
fi
HERDR_COLLIE_CONFIG="${HERDR_COLLIE_CONFIG:-$HERDR_COLLIE_CONFIG_DEFAULT}"

# Foundry repo = where work-board.sh lives. CWD-independent so the script
# works the same from cron, a launcher button, or `work-board refresh`.
FOUNDRY_REPO_DEFAULT="/home/home/imapps/foundry"
FOUNDRY_REPO="${FOUNDRY_REPO:-$FOUNDRY_REPO_DEFAULT}"
WORK_BOARD="$FOUNDRY_REPO/bin/work-board.sh"

# Dotfiles path. Override via DOTFILES_HOME for non-default layouts.
DOTFILES_HOME_DEFAULT="${DOTFILES_HOME:-$HOME/dotfiles}"
DOTFILES_LAUNCHERS="$DOTFILES_HOME_DEFAULT/herdr/.config/herdr/plugins/config/herdr.collie/launchers.toml"

if [ ! -x "$WORK_BOARD" ]; then
  echo "regen-launchers: work-board.sh not found / not executable at $WORK_BOARD" >&2
  exit 4
fi
if ! command -v jott >/dev/null 2>&1; then
  echo "regen-launchers: jott not on PATH (workboards are jott-backed)" >&2
  exit 4
fi
if ! command -v jq >/dev/null 2>&1; then
  echo "regen-launchers: jq not on PATH (needed to parse jott --json output)" >&2
  exit 4
fi

mkdir -p "$HERDR_COLLIE_CONFIG"

# Pull the project list once, fail loudly if jott is unhappy. Empty list is
# legal (no projects yet), in which case only the always-on rows go in.
projects_json="$(jott task projects --json)" || {
  echo "regen-launchers: 'jott task projects --json' failed" >&2
  exit 5
}

# Write the file in one pass: header + per-project rows + always-on rows.
# The schema requires each `command` to be a SHELL LINE; a bare token like
# "all" would just exec the `all` builtin (`bash: all: command not found`),
# so each command is an absolute-path invocation of work-board.sh. cwd is
# pinned per row so a tap on the dashboard and a tap on a pane both open
# in the project (not in foundry).
{
  cat <<HEADER
# Generated by foundry/bin/regen-launchers.sh — do not hand-edit.
# This file is the allowlist for POST /api/launch; editing it by hand works
# but is overwritten the next time \`work-board refresh\` (or this regen
# script) runs. To add a new button, add the jott project first, then
# re-run this script. See foundry/docs/homelab.md and the comments at the
# top of launchers.toml.example in the plugin repo for the schema.
HEADER

  # Project names are jott's `^[a-z0-9][a-z0-9-]*$` namespace, so no
  # quoting hazards inside a TOML basic string. If jott ever grows escaping
  # needs, swap @sh for proper TOML escaping (tomli/tomllib) here.
  printf '%s' "$projects_json" | jq -r '
    (.projects // [])
    | sort_by(.name)
    | .[]
    | "  [[launchers]]\n  command = \"/home/home/imapps/foundry/bin/work-board.sh \(.name)\"\n  label = \"Work \(.name)\"\n  cwd = \"/home/home/imapps/\(.name)\"\n"
  '

  cat <<'ALWAYS'

# Always-on meta-board actions. These run from the foundry repo, not from
# any one app's checkout — they're the cross-cutting kanban operations.
[[launchers]]
command = "/home/home/imapps/foundry/bin/work-board.sh all"
label = "All projects"
cwd = "/home/home/imapps/foundry"

[[launchers]]
command = "/home/home/imapps/foundry/bin/work-board.sh refine"
label = "Refine inbox"
cwd = "/home/home/imapps/foundry"

[[launchers]]
command = "/home/home/imapps/foundry/bin/work-board.sh triage"
label = "Triage blocked"
cwd = "/home/home/imapps/foundry"

[[launchers]]
command = "/home/home/imapps/foundry/bin/work-board.sh refresh"
label = "Refresh boards"
cwd = "/home/home/imapps/foundry"
ALWAYS
} > "$HERDR_COLLIE_CONFIG/launchers.toml"

# Mirror to the dotfiles repo. Re-stow will symlink the canonical path back
# to this dotfile; either way, regen writes through to the durable source.
if [ -d "$DOTFILES_HOME_DEFAULT/herdr" ]; then
  mkdir -p "$(dirname "$DOTFILES_LAUNCHERS")"
  cp "$HERDR_COLLIE_CONFIG/launchers.toml" "$DOTFILES_LAUNCHERS"
  echo "regen-launchers: wrote $HERDR_COLLIE_CONFIG/launchers.toml + mirrored to dotfiles $DOTFILES_LAUNCHERS" >&2
else
  echo "regen-launchers: wrote $HERDR_COLLIE_CONFIG/launchers.toml (no dotfiles repo at $DOTFILES_HOME_DEFAULT, skipping mirror)" >&2
fi

# Sanity: confirm the file is parseable TOML. `tomllib` ships in Python
# 3.11+. If neither is available we skip silently — the file is still
# written and herdr reload-config is what actually validates it on read.
if command -v python3 >/dev/null 2>&1; then
  python3 -c "
import sys
try:
    import tomllib
except ImportError:
    try:
        import tomli as tomllib
    except ImportError:
        sys.exit(0)
with open('$HERDR_COLLIE_CONFIG/launchers.toml', 'rb') as f:
    data = tomllib.load(f)
rows = data.get('launchers', [])
print(f'regen-launchers: TOML parses, {len(rows)} launcher rows', file=sys.stderr)
"
fi

# Tell herdr to reload so the new buttons surface immediately. Don't fail
# the script if herdr isn't running — `work-board refresh` is also called
# from a launcher button whose spawn already opens a fresh session.
if command -v herdr >/dev/null 2>&1; then
  if herdr server reload-config >/dev/null 2>&1; then
    echo "regen-launchers: herdr server reload-config OK" >&2
  else
    echo "regen-launchers: herdr server reload-config failed (server not running?); buttons refresh on next client reload" >&2
  fi
fi
